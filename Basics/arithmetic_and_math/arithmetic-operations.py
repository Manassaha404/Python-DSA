

# addition
value = 0
value = value + 1
print(f"Value after addition: {value}")


# subtraction
value = 0
value = value - 6
print(f"Value after subtraction: {value}")


# multiplication
value = 0
value = value * 1
print(f"Value after multiplication: {value}")


# division
value = 13
value = value / 2
print(f"Value of 13 / 2: {value}")

# modulus
value = 13
value = value % 2
print(f"Value of 13 % 2: {value}")

# remainder
value = 13
value = value // 2
print(f"Value of 13 // 2: {value}")

# exponentiation
value = 2
value = value ** 3
print(f"Value of 2 ** 3: {value}")

# bodmas = (2 + 3) * 4
value = (2 + 3) * 4
print(f"Value of (2 + 3) * 4: {value}")


# value = value + 1 -> value += 1
# value = value - 1 -> value -= 1
# value = value * 1 -> value *= 1
# value = value / 1 -> value /= 1
# value = value ** value -> value **= value