# variable = A container for storing data values


## Data Types:

# string
first_name = "Manas"
email = "manas123@gmail.com"
print(first_name) # how to print a variable
print(f"Email: {email}") # how to print a variable inside a string using f-string(format string) 


# integer
age = 25
print(f"Age: {age}")

# float
height = 6.1
print(f"Height: {height}")

# boolean
is_student = True
print(f"Is Student: {is_student}")
